
public class Switch {
    public static void main(String[] args) {
        char ch = 'a';
        switch (ch) {
            case 'd':
                System.out.println("hello");
                break;
            case 'a':
                System.out.println("hi");
                break;
            case 'c':
                System.out.println("namaste");
                break;
            default:
                System.out.println("error");

        }
    }
}
